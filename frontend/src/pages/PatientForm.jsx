import { useEffect, useState } from 'react';
import { Link, useNavigate, useParams } from 'react-router-dom';
import { CheckCircle2, Save } from 'lucide-react';
import { api, errorMessage, fieldErrors } from '../lib/api';
import { useToast } from '../components/Toast';
import { useAuth } from '../auth/AuthContext';
import { Alert, Button, Card, DateInput, ErrorState, Input, Select, Spinner, Textarea } from '../components/ui';
import { PageHeader } from '../components/domain';
import { todayIso } from '../lib/format';

const EMPTY = { fullName: '', dateOfBirth: '', gender: '', contactNumber: '', email: '', address: '', emergencyContactName: '', emergencyContactNumber: '', correctionReason: '' };
const PHONE = /^[+]?[0-9][0-9 -]{6,18}[0-9]$/;
const NAME = /^[A-Za-z\u00C0-\u024F .'-]+$/;

function validate(f, editing, isAdmin) {
  const e = {};
  const name = f.fullName.trim();
  if (!name) e.fullName = 'Full name is required';
  else if (name.length < 2) e.fullName = 'Name must be at least 2 characters';
  else if (!NAME.test(name)) e.fullName = 'Name can contain letters, spaces, dots, apostrophes and hyphens';
  if (!f.dateOfBirth) e.dateOfBirth = 'Date of birth is required';
  else if (f.dateOfBirth >= todayIso()) e.dateOfBirth = 'Date of birth must be in the past';
  else if (f.dateOfBirth < '1900-01-01') e.dateOfBirth = 'Enter a date after 1900';
  if (!f.gender) e.gender = 'Select a gender';
  if (!f.contactNumber.trim()) e.contactNumber = 'Contact number is required';
  else if (!PHONE.test(f.contactNumber.trim())) e.contactNumber = 'Enter a valid phone number, e.g. +91 98765 43210';
  if (f.email && !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(f.email.trim())) e.email = 'Enter a valid email address';
  if (f.emergencyContactNumber && !PHONE.test(f.emergencyContactNumber.trim())) e.emergencyContactNumber = 'Enter a valid phone number';
  if (editing && isAdmin && !f.correctionReason.trim()) e.correctionReason = 'Admin corrections require a reason for the audit log';
  return e;
}

export default function PatientForm() {
  const { id } = useParams();
  const editing = !!id;
  const { hasRole } = useAuth();
  const navigate = useNavigate();
  const toast = useToast();
  const [form, setForm] = useState(EMPTY);
  const [errors, setErrors] = useState({});
  const [saving, setSaving] = useState(false);
  const [failure, setFailure] = useState(null);
  const [created, setCreated] = useState(null);
  const [loadState, setLoadState] = useState({ loading: editing, error: null });

  useEffect(() => {
    if (!editing) return;
    api.get(`/patients/${id}`).then((res) => {
      const p = res.data.patient;
      setForm({ ...EMPTY, ...Object.fromEntries(Object.keys(EMPTY).map((k) => [k, p[k] ?? ''])), correctionReason: '' });
      setLoadState({ loading: false, error: null });
    }).catch((e) => setLoadState({ loading: false, error: errorMessage(e) }));
  }, [editing, id]);

  const set = (k) => (e) => setForm((f) => ({ ...f, [k]: e.target.value }));

  const submit = async (e) => {
    e.preventDefault();
    const v = validate(form, editing, hasRole('ADMIN'));
    setErrors(v);
    setFailure(null);
    if (Object.keys(v).length) return;
    setSaving(true);
    const body = Object.fromEntries(Object.entries(form).map(([k, val]) => [k, typeof val === 'string' && val.trim() === '' ? null : val]));
    try {
      if (editing) {
        await api.put(`/patients/${id}`, body);
        toast.success('Patient details updated.');
        navigate(`/patients/${id}`);
      } else {
        const res = await api.post('/patients', body);
        setCreated(res.data);
        toast.success(`Patient registered as ${res.data.patientCode}.`);
      }
    } catch (err) {
      setErrors(fieldErrors(err));
      setFailure(errorMessage(err, 'The patient could not be saved.'));
    } finally {
      setSaving(false);
    }
  };

  if (loadState.loading) return <Spinner label="Loading patient" />;
  if (loadState.error) return <ErrorState message={loadState.error} />;

  if (created) {
    return (
      <Card className="mx-auto max-w-xl">
        <div className="flex flex-col items-center py-4 text-center">
          <CheckCircle2 className="h-9 w-9 text-ok-600" aria-hidden />
          <h1 className="mt-3 text-xl font-semibold">{created.fullName} is registered</h1>
          <p className="mt-2 text-sm text-ink-muted">Patient ID generated by the server</p>
          <p className="mt-1 font-mono text-2xl text-brand-700">{created.patientCode}</p>
          <div className="mt-6 flex flex-wrap justify-center gap-2">
            <Button onClick={() => navigate(`/admissions/new?patientId=${created.id}`)}>Create admission</Button>
            <Button variant="secondary" onClick={() => navigate(`/patients/${created.id}`)}>Open profile</Button>
            <Button variant="ghost" onClick={() => { setCreated(null); setForm(EMPTY); }}>Register another</Button>
          </div>
        </div>
      </Card>
    );
  }

  return (
    <>
      <PageHeader
        title={editing ? 'Correct patient details' : 'Register patient'}
        description={editing ? 'Changes are recorded in the audit log.' : 'The Patient ID is generated by the server when you save.'}
        breadcrumbs={[{ label: 'Patients', to: '/patients' }, ...(editing ? [{ label: 'Profile', to: `/patients/${id}` }] : []), { label: editing ? 'Correct details' : 'Register' }]}
      />
      <form onSubmit={submit} noValidate className="max-w-3xl">
        <Card>
          {failure && <div className="mb-4"><Alert tone="bad" title="Not saved">{failure}</Alert></div>}
          <fieldset className="grid gap-4 sm:grid-cols-2">
            <legend className="mb-3 text-sm font-semibold uppercase tracking-wide text-ink-muted">Demographics</legend>
            <Input label="Full name" required value={form.fullName} onChange={set('fullName')} error={errors.fullName} autoComplete="off" className="sm:col-span-2" />
            <DateInput label="Date of birth" required max={todayIso()} min="1900-01-01" value={form.dateOfBirth} onChange={set('dateOfBirth')} error={errors.dateOfBirth} hint="Age is calculated from this date." />
            <Select label="Gender" required value={form.gender} onChange={set('gender')} error={errors.gender}>
              <option value="">Select</option><option value="FEMALE">Female</option><option value="MALE">Male</option><option value="OTHER">Other</option>
            </Select>
            <Input label="Contact number" required type="tel" value={form.contactNumber} onChange={set('contactNumber')} error={errors.contactNumber} placeholder="+91 98765 43210" />
            <Input label="Email" type="email" value={form.email} onChange={set('email')} error={errors.email} />
            <Textarea label="Address" rows={2} value={form.address} onChange={set('address')} error={errors.address} className="sm:col-span-2" />
          </fieldset>
          <fieldset className="mt-6 grid gap-4 border-t border-line pt-5 sm:grid-cols-2">
            <legend className="sr-only">Emergency contact</legend>
            <p className="text-sm font-semibold uppercase tracking-wide text-ink-muted sm:col-span-2">Emergency contact (optional)</p>
            <Input label="Name" value={form.emergencyContactName} onChange={set('emergencyContactName')} error={errors.emergencyContactName} />
            <Input label="Phone" type="tel" value={form.emergencyContactNumber} onChange={set('emergencyContactNumber')} error={errors.emergencyContactNumber} />
          </fieldset>
          {editing && (
            <div className="mt-6 border-t border-line pt-5">
              <Textarea label="Reason for correction" required={hasRole('ADMIN')} rows={2} value={form.correctionReason} onChange={set('correctionReason')} error={errors.correctionReason} />
            </div>
          )}
          <div className="mt-6 flex flex-wrap justify-end gap-2 border-t border-line pt-5">
            <Link to={editing ? `/patients/${id}` : '/patients'} className="inline-flex h-10 items-center rounded px-4 text-sm font-semibold text-ink-soft hover:bg-sunken">Cancel</Link>
            <Button type="submit" loading={saving} icon={Save}>{editing ? 'Save correction' : 'Register patient'}</Button>
          </div>
        </Card>
      </form>
    </>
  );
}
